let gameSeq = [];
let userSeq = [];

let btns = ["red", "yellow", "purple", "green"];

let started = false;
let level = 0;
let HighestScore = 0;

let h2 = document.querySelector("h2");

document.addEventListener("keypress", function () {
    if (started == false) {
        console.log("game is started");
        started = true;

        levelUp();
    }
});

function gameFlash(btn) {
    btn.classList.add("flash");
    setTimeout(function () {
        btn.classList.remove("flash");
    }, 250);
}

function userFlash(btn) {
    btn.classList.add("userflash");
    setTimeout(function () {
        btn.classList.remove("userflash");
    }, 250);
}


function levelUp() {
    userSeq = [];
    level++;
    if(level > HighestScore) {
        HighestScore = level;
    }

    h2.innerHTML = `Level ${level}`;//here we use innerHTML because innertext ke andar tag nhi de sakte

    let randIdx = Math.floor(Math.random() * 4);
    let randColor = btns[randIdx];
    let randBtn = document.querySelector(`.${randColor}`);
    // console.log(randIdx);
    // console.log(randColor);
    // console.log(randBtn);
    gameSeq.push(randColor); //here we print the random color generated by game
    console.log(gameSeq);
    gameFlash(randBtn);
}

function checkAns(idx) { //here idx becomes our argument because of line 81 for that index we check our value
    // console.log("curr level : ", level);  //here we make a function first that prints the current level 

    if(userSeq[idx] == gameSeq[idx]) {
        if (userSeq.length == gameSeq.length) {
            setTimeout(levelUp, 1000); //call the levelUp function
        }
    } else {
        h2.innerHTML = `Game Over! Your score was <b>${level}</b> <br> Press any key to start. <br> High Score: ${HighestScore}`;
        document.querySelector("body").style.backgroundColor = "red";
        setTimeout(function() {
            document.querySelector("body").style.backgroundColor = "white";
        }, 150);
        reset(); //after game is over we have to reset the function
    }
}

function btnPress() {
    //console.log(this); //we wrote this line so we can track the record of button which we pressed
    let btn = this; //here 'this' is our button that we clicked or pressed(remember that in our code we have so many btn but they are not clashed with each other because they are used inside their function and in their loops)
    userFlash(btn);  

    userColor = btn.getAttribute("id");
    userSeq.push(userColor);

    checkAns(userSeq.length-1);
}

let allBtns = document.querySelectorAll(".btn");
for (btn of allBtns) {
    btn.addEventListener("click", btnPress);
}

function reset() {
    started = false;
    gameSeq = [];
    userSeq = [];
    level = 0;
}